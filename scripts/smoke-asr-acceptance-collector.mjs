#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { spawnSync } from "node:child_process";

const collectorPath = "scripts/collect-asr-acceptance-evidence.mjs";
const outputPath = ".data/smoke/asr-collector-latest.md";
const emptySamplePath = ".data/smoke/asr-collector-empty.wav";

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(emptySamplePath, Buffer.alloc(0));

const source = readFileSync(collectorPath, "utf8");
const packageJson = JSON.parse(readFileSync("package.json", "utf8"));
const runbook = readFileSync("docs/asr-runtime-runbook.md", "utf8");

const noSample = spawnSync("node", [collectorPath, `--output=${outputPath}`, "--skip-sample=1"], {
  encoding: "utf8",
  env: cleanEnv(),
});
const noSamplePayload = parseJson(noSample.stdout);
const noSampleEvidence = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
const draftCheck = spawnSync("node", ["scripts/check-asr-acceptance-evidence.mjs"], {
  encoding: "utf8",
  env: {
    ...process.env,
    OWNMINUTES_ASR_ACCEPTANCE_EVIDENCE_PATH: outputPath,
  },
});
const draftCheckPayload = parseJson(draftCheck.stdout);

const emptySample = spawnSync("node", [collectorPath, `--output=${outputPath}`, `--sample=${emptySamplePath}`], {
  encoding: "utf8",
  env: cleanEnv(),
});
const emptySamplePayload = parseJson(emptySample.stdout);

const summary = {
  packageScriptExists: packageJson.scripts["asr:acceptance:collect"] === "node scripts/collect-asr-acceptance-evidence.mjs",
  smokeScriptExists: packageJson.scripts["smoke:asr-acceptance-collector"] === "node scripts/smoke-asr-acceptance-collector.mjs",
  structuredBatchScriptsExist:
    packageJson.scripts["asr:meeting-batch:collect"] === "node scripts/collect-asr-meeting-batch-evidence.mjs" &&
    packageJson.scripts["asr:meeting-batch:check"] === "node scripts/check-asr-meeting-batch-evidence.mjs" &&
    packageJson.scripts["smoke:asr-meeting-batch"] === "node scripts/smoke-asr-meeting-batch-evidence.mjs",
  collectorUsesPreflight: source.includes("scripts/check-asr-production-env.mjs"),
  collectorCanRunSample: source.includes("scripts/run-asr-sample-transcription.mjs"),
  collectorWritesPrivateAcceptancePath: source.includes(".data/acceptance/asr-latest.md"),
  collectorKeepsFormalDecisionPending:
    source.includes("- Decision: pending") &&
    source.includes("releaseGateReady: false") &&
    source.includes("formalDecision: \"pending\"") &&
    source.includes("speakerDecision: \"pending\""),
  collectorRedactsSecrets: source.includes("redactSecrets") && source.includes("secretFragments") && source.includes("[redacted]"),
  noSampleCollectorOk:
    noSample.status === 0 &&
    noSamplePayload?.ok === true &&
    noSamplePayload?.releaseGateReady === false &&
    noSamplePayload?.sampleStatus === "skipped" &&
    noSampleEvidence.includes("This file was generated by `npm run asr:acceptance:collect`.") &&
    noSampleEvidence.includes("Result status: pending") &&
    noSampleEvidence.includes("Realtime vs post-meeting boundary") &&
    noSampleEvidence.includes("## Structured Meeting Batch") &&
    noSampleEvidence.includes(".data/acceptance/asr-meeting-batch-latest.json") &&
    noSampleEvidence.includes("Provider preflight missing:"),
  collectorDraftRejectedByFormalChecker:
    draftCheck.status !== 0 &&
    draftCheckPayload?.evidenceReady === false &&
    draftCheckPayload?.missingFields?.includes("Result status: transcribed") &&
    draftCheckPayload?.passDecisionCount === 0,
  emptySampleStillWritesPendingDraft:
    emptySample.status === 0 &&
    emptySamplePayload?.ok === true &&
    emptySamplePayload?.sampleStatus === "failed" &&
    emptySamplePayload?.sampleDecision === "fail" &&
    emptySamplePayload?.releaseGateReady === false,
  runbookMentionsCollector:
    runbook.includes("npm run asr:acceptance:collect") &&
    runbook.includes("OWNMINUTES_ASR_ACCEPTANCE_COLLECT_PATH") &&
    runbook.includes("asr:acceptance:collect writes a private evidence draft") &&
    runbook.includes("npm run asr:meeting-batch:check"),
  leaksSecrets:
    noSampleEvidence.includes("AKL") ||
    noSampleEvidence.includes("sk-proj") ||
    noSampleEvidence.includes("Secret Access Key") ||
    noSampleEvidence.includes("WVRCaE") ||
    source.includes("asr-live-key") ||
    source.includes("runtime-token"),
};

console.log(JSON.stringify(summary, null, 2));

const { leaksSecrets, ...positiveChecks } = summary;

if (Object.values(positiveChecks).some((value) => value === false) || leaksSecrets) {
  process.exitCode = 1;
}

function cleanEnv() {
  const env = { ...process.env };
  delete env.OWNMINUTES_ASR_SAMPLE_PATH;
  delete env.OWNMINUTES_ASR_EXPECTED_PHRASE;
  delete env.OWNMINUTES_ASR_ACCEPTANCE_COLLECT_PATH;
  delete env.VOLCANO_ASR_API_KEY;
  delete env.VOLCANO_ASR_APP_ID;
  delete env.VOLCANO_ASR_TOKEN;
  delete env.ARK_API_KEY;
  return env;
}

function parseJson(text = "") {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start < 0 || end < start) return null;
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return null;
  }
}
