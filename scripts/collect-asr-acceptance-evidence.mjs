import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { spawnSync } from "node:child_process";

loadDotEnvLocal();

const options = parseArgs(process.argv.slice(2));
const outputPath = options.output || process.env.OWNMINUTES_ASR_ACCEPTANCE_COLLECT_PATH || ".data/acceptance/asr-latest.md";
const samplePath = options.sample || process.env.OWNMINUTES_ASR_SAMPLE_PATH || "";
const expectedPhrase = options.expected || process.env.OWNMINUTES_ASR_EXPECTED_PHRASE || "";
const skipSample = options.skipSample === "1" || options.skipSample === "true" || process.env.OWNMINUTES_ASR_COLLECT_SKIP_SAMPLE === "1";
