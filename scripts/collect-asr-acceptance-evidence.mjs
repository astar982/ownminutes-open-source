function runSample(path, expected) {
  const args = ["scripts/run-asr-sample-transcription.mjs", `--sample=${path}`];
  if (expected) args.push(`--expected=${expected}`);
  const result = runCommand("node", args);
  const payload = result.payload ?? {};
  return {
    command: `node ${args.map(shellEscape).join(" ")}`,
    decision: payload.decision ?? "fail",
    duration: process.env.OWNMINUTES_ASR_SAMPLE_DURATION_MS ? `${process.env.OWNMINUTES_ASR_SAMPLE_DURATION_MS} ms` : "pending",
    evidencePath: payload.evidencePath ?? null,
    expectedPhraseReadable: payload.expectedPhraseReadable,
    exitCode: result.status,
    mimeType: inferMimeType(path),
    requestId: payload.requestId,
    status: payload.status ?? "failed",
    testPath: "CLI sample",
    transcriptPreview: readTranscriptPreview(payload.evidencePath),
  };
}

function skippedSample() {
  return {
    command: "skipped by OWNMINUTES_ASR_COLLECT_SKIP_SAMPLE",
    decision: "pending",
    exitCode: 0,
    status: "skipped",
    testPath: "pending",
  };
}

function missingSample() {
  return {
    command: "missing OWNMINUTES_ASR_SAMPLE_PATH",
    decision: "pending",
    exitCode: 1,
    status: "missing_sample",
    testPath: "pending",
  };
}

function runCommand(command, args, extraEnv = {}) {
  const result = spawnSync(command, args, {
    encoding: "utf8",
    env: { ...process.env, ...extraEnv },
    maxBuffer: 1024 * 1024,
  });
  const output = `${result.stdout || ""}${result.stderr || ""}`.trim();
  return {
    status: result.status ?? 1,
    output: redactSecrets(output),
    payload: parseJson(result.stdout) ?? parseJson(output),
  };
}

function parseArgs(args) {
  const parsed = {};
  for (const arg of args) {
    if (!arg.startsWith("--")) continue;
    const [rawKey, ...rest] = arg.slice(2).split("=");
    const key = rawKey.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    parsed[key] = rest.join("=") || "1";
  }
  return parsed;
}

function parseJson(text = "") {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start < 0 || end < start) return null;
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return null;
  }
}

function readTranscriptPreview(path) {
  if (!path || !existsSync(path)) return "";
  const text = readFileSync(path, "utf8");
  const match = text.match(/^- Transcript preview:\s*(.+)$/m);
  return match ? match[1].trim().slice(0, 260) : "";
}

function inferMimeType(filePath) {
  const lower = filePath.toLowerCase();
  if (lower.endsWith(".wav")) return "audio/wav";
  if (lower.endsWith(".mp3")) return "audio/mpeg";
  if (lower.endsWith(".m4a") || lower.endsWith(".mp4")) return "audio/mp4";
  if (lower.endsWith(".aac")) return "audio/aac";
  if (lower.endsWith(".webm")) return "audio/webm";
  if (lower.endsWith(".ogg")) return "audio/ogg";
  return "application/octet-stream";
}

function shellEscape(value) {
  return String(value).includes(" ") ? JSON.stringify(String(value)) : String(value);
}

function findSecretLeaks(text) {
  return secretFragments().filter((fragment) => fragment && text.includes(fragment));
}

function redactSecrets(value) {
  let output = value;
  for (const fragment of secretFragments()) {
    output = output.split(fragment).join("[redacted]");
  }
  return output;
}

function secretFragments() {
  return [
    process.env.VOLCANO_ASR_API_KEY,
    process.env.VOLCANO_ASR_TOKEN,
    process.env.ARK_API_KEY,
    process.env.OPENAI_API_KEY,
    process.env.VOLCANO_ACCESS_KEY_ID,
    process.env.VOLCANO_SECRET_ACCESS_KEY,
    "AKL",
    "sk-proj",
    "Secret Access Key",
    "WVRCaE",
    "-----BEGIN PRIVATE KEY-----",
    "BEGIN OPENSSH PRIVATE KEY",
  ].filter((value) => typeof value === "string" && value.length >= 6);
}

function loadDotEnvLocal() {
  if (!existsSync(".env.local")) return;

  const contents = readFileSync(".env.local", "utf8");
  for (const line of contents.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex < 0) continue;
    const key = trimmed.slice(0, separatorIndex);
    const value = trimmed.slice(separatorIndex + 1);
    if (!process.env[key]) process.env[key] = stripQuotes(value);
  }
}

function stripQuotes(value) {
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    return value.slice(1, -1);
  }
  return value;
}
